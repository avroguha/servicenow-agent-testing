"""MID Server side of ACC: the WebSocket listener the agents connect to, and the API key they authenticate with.

Facts verified on the instance (ACC Framework 7.1.3):
  * The listener is two MID extension contexts: a "Mid Web Server" (ecc_agent_ext_context_webserver, port 8800,
    authentication_type 3 = API key, secure) and an "ACC Websocket Endpoint" (sn_agent_ext_context) whose
    endpoint_url is wss://<mid ip>:<port>/ws/events. ``sn_agent.AgentNowSetup().setupExt(mid, port, ip)`` builds both,
    exactly like the "Setup ACC Listener" button on the MID Server form.
  * API keys live in mid_webserver_api_key_credentials. The key VALUE is generated by the business rule
    "Generate API Key" on insert - a record is created with an EMPTY authentication_key and the value is read back
    with ``sn_agent.AgentSingleLineInstallerCommands().getApiKeyBySysId()`` (KMF-aware). A plain
    getDecryptedValue() returns garbage for KMF-protected keys. At most mid.webserver.max.api.keys (10) keys exist.
"""
from __future__ import annotations

import json
import logging
import time

from .config import Settings
from .snow import SNClient, SNError

LOG = logging.getLogger("acctest.mid")


def mid_record(sn: SNClient, name: str) -> dict | None:
    return sn.first("ecc_agent", f"name={name}", "sys_id,name,status,validated,ip_address,host_name,version,last_refreshed")


def listener_status(sn: SNClient, mid_name: str) -> dict:
    """What the instance knows about the ACC listener of this MID."""
    ws = sn.first("ecc_agent_ext_context_webserver", f"mid_server.name={mid_name}",
                  "sys_id,name,status,error_message,port_number,secure_connection,authentication_type")
    ep = sn.first("sn_agent_ext_context", f"mid_server.name={mid_name}",
                  "sys_id,name,status,error_message,endpoint_url,endpoint_url_ipv6,ip_address")
    return {"webserver": ws, "endpoint": ep,
            "ready": bool(ws and ep and ws.get("status") == "Started" and ep.get("status") == "Started"),
            "endpoint_url": (ep or {}).get("endpoint_url", "")}


def ensure_listener(sn: SNClient, settings: Settings, wait_s: int = 240) -> dict:
    """Make sure the MID has a started web server + websocket endpoint. Creates them when MID_AUTO_CONFIGURE is on."""
    mid = mid_record(sn, settings.mid_server_name)
    if not mid:
        raise SNError(f"MID Server '{settings.mid_server_name}' not found on the instance")
    if mid["status"] != "Up" or mid["validated"] != "true":
        raise SNError(f"MID Server '{mid['name']}' is {mid['status']}, validated={mid['validated']} - it must be Up and validated")
    st = listener_status(sn, mid["name"])
    if st["ready"]:
        return {"mid": mid, **st, "action": "existing"}
    if not settings.mid_auto_configure:
        raise SNError("ACC listener on %s is not ready (web server=%s, endpoint=%s) and MID_AUTO_CONFIGURE=false"
                      % (mid["name"], (st["webserver"] or {}).get("status"), (st["endpoint"] or {}).get("status")))
    LOG.info("setting up the ACC listener on MID %s (port %s, ip %s)", mid["name"], settings.mid_ws_port, settings.mid_host)
    ip = settings.mid_host if _looks_like_ipv4(settings.mid_host) else (mid.get("ip_address") or "")
    js = ("var r = new sn_agent.AgentNowSetup().setupExt('%s', '%s', %s); OUT({setup: r});"
          % (mid["sys_id"], settings.mid_ws_port, json.dumps(ip) if ip else "null"))
    out = sn.run_script(js, 240, "acc-listener-setup")
    setup = json.loads(out[0]["setup"]) if out and isinstance(out[0].get("setup"), str) else out
    LOG.info("setup result: %s", setup)
    deadline = time.time() + wait_s
    while time.time() < deadline:
        st = listener_status(sn, mid["name"])
        if st["ready"]:
            return {"mid": mid, **st, "action": "created", "setup": setup}
        time.sleep(10)
    raise SNError(f"ACC listener did not reach Started on {mid['name']}: {st}")


def _looks_like_ipv4(s: str) -> bool:
    parts = s.split(".")
    return len(parts) == 4 and all(p.isdigit() and 0 <= int(p) <= 255 for p in parts)


def list_api_keys(sn: SNClient) -> list[dict]:
    return sn.query("mid_webserver_api_key_credentials", "active=true", "sys_id,name,expires,expiration_time,sys_created_on", 50)


def read_api_key_value(sn: SNClient, sys_id: str) -> str:
    js = "OUT({key: new sn_agent.AgentSingleLineInstallerCommands().getApiKeyBySysId('%s')});" % sys_id
    out = sn.run_script(js, 120, "api-key-read")
    key = (out[0] or {}).get("key", "") if out else ""
    if not key or key == "<api-key>":
        raise SNError(f"could not read the value of API key {sys_id} (got {key!r})")
    return key


def ensure_api_key(sn: SNClient, settings: Settings) -> dict:
    """Return {'key': value, 'sys_id': ..., 'name': ..., 'action': used|existing|created}.
    ACC_API_KEY set -> used as given. Otherwise the record named ACC_API_KEY_NAME is read (or created when
    ACC_API_KEY_AUTO_CREATE is on), and the value is written back into .env."""
    if settings.acc_api_key:
        return {"key": settings.acc_api_key, "sys_id": "", "name": "(from .env)", "action": "used"}
    rec = sn.first("mid_webserver_api_key_credentials", f"name={settings.acc_api_key_name}^active=true", "sys_id,name")
    action = "existing"
    if not rec:
        if not settings.acc_api_key_auto_create:
            raise SNError("ACC_API_KEY is empty, no active API key named %r exists and ACC_API_KEY_AUTO_CREATE=false"
                          % settings.acc_api_key_name)
        LOG.info("creating API key record %r", settings.acc_api_key_name)
        rec = sn.insert("mid_webserver_api_key_credentials", {"name": settings.acc_api_key_name, "active": "true", "expires": "false"})
        action = "created"
    key = read_api_key_value(sn, rec["sys_id"])
    settings.write_back("ACC_API_KEY", key)
    settings.acc_api_key = key
    return {"key": key, "sys_id": rec["sys_id"], "name": rec["name"], "action": action}


def mid_agents_count(sn: SNClient, mid_name: str) -> int:
    return sn.count("sn_agent_ci_extended_info", f"mid.name={mid_name}")


# ---- plugin cache ---------------------------------------------------------------------------------------------------
def assets_state(sn: SNClient, mid_name: str) -> dict:
    """Did the ACC plugin assets (sn_agent_asset) change after the MID last started? A MID keeps the hash of each
    plugin it serves from startup; when the app is (re)installed afterwards the agents fail with ACC-1500
    'hash of the file does not match expected hash' until the MID restarts (seen 2026-11-07, Brazil)."""
    started = (sn.first("ecc_agent", f"name={mid_name}", "started") or {}).get("started", "")
    # an app install/upgrade stamps sys_updated_on on the asset records (sys_created_on keeps the vendor's date)
    newest = sn.first("sn_agent_asset", "directory=false^ORDERBYDESCsys_updated_on", "name,sys_updated_on") or {}
    apps = sn.query("sys_scope", "scopeINsn_agent,sn_acc_vis_content,sn_itmon,sn_accl^ORDERBYDESCsys_updated_on", "scope,sys_updated_on", 1)
    changed = max([newest.get("sys_updated_on", "")] + [a.get("sys_updated_on", "") for a in apps])
    return {"mid_started": started, "assets_changed": changed, "newest_asset": newest.get("name", ""),
            "stale": bool(started and changed and changed > started), "asset_count": sn.count("sn_agent_asset", "directory=false")}


def restart_mid(sn: SNClient, mid_name: str, wait_s: int = 420) -> dict:
    """Restart the MID through the platform (MIDServerManage) and wait until it is Up again with a new start time."""
    before = (sn.first("ecc_agent", f"name={mid_name}", "started") or {}).get("started", "")
    sn.run_script("new global.MIDServerManage().restart(%s); OUT({ok: true});" % json.dumps(mid_name), 120, "mid-restart")
    deadline = time.time() + wait_s
    while time.time() < deadline:
        m = sn.first("ecc_agent", f"name={mid_name}", "status,started") or {}
        if m.get("status") == "Up" and m.get("started", "") > before:
            time.sleep(15)  # let the extensions come up
            return {"restarted": True, "started": m["started"]}
        time.sleep(15)
    return {"restarted": False, "started": before}


def sync_plugins(sn: SNClient, mid_name: str, restart: bool = True) -> dict:
    """Push the cached resources list to the MID (the 'Sync all resources on all MIDs' action) and, by default,
    restart the MID so that it re-reads every plugin asset it serves."""
    out = {"assets": assets_state(sn, mid_name)}
    # MidResourceCache (the "Sync all resources" action) is package-private and cannot be called from a global
    # script; a restart makes the MID re-sync every sn_agent_asset file anyway, so the restart is the remedy.
    out["sync_sent"] = False
    if restart:
        out["restart"] = restart_mid(sn, mid_name)
        st = listener_status(sn, mid_name)
        out["listener_ready"] = st["ready"]
    return out


# ---- customer plugin-signing certificates ----------------------------------------------------------------------------
# The agent accepts a custom plugin only when its .sig verifies with a certificate it holds; customer certificates reach
# the agent as a zip the MID serves from <MID home>/agent/static/cert/customer/. There is no instance-side upload for
# that directory - the zip is copied onto the MID host (MID_SSH_TARGET = user@host or pct:<vmid>), or by hand.
def customer_cert_dir(settings: Settings) -> str:
    home = settings.mid_home
    sep = "\\" if (":" in home[:3] or "\\" in home) else "/"
    return f"{home}{sep}agent{sep}static{sep}cert{sep}customer" if home else ""


def publish_customer_certs(settings: Settings, zip_path, remove_pattern: str = "acctest-customer-certs-*.zip") -> dict:
    """Copy the certificate zip onto the MID host. Older zips matching remove_pattern are removed first so agents are
    not offered a stale certificate. Returns {published, path, how, error}."""
    import shlex
    import subprocess
    from pathlib import Path
    from .targets import _scp_base, _ssh_base
    zip_path = Path(zip_path)
    target, home = settings.mid_ssh_target, settings.mid_home
    out: dict = {"published": False, "how": target, "dir": customer_cert_dir(settings)}
    if not target or not home:
        out["error"] = "MID_SSH_TARGET / MID_HOME not set - copy the zip to <MID home>/agent/static/cert/customer/ by hand"
        return out
    d = out["dir"]
    try:
        if target.startswith("pct:"):
            vmid = int(target.split(":", 1)[1])
            node = f"{settings.pve_user}@{settings.pve_host}"
            tmp = f"/tmp/{zip_path.name}"
            r = subprocess.run(_scp_base(settings.pve_ssh_key) + [str(zip_path), f"{node}:{tmp}"], capture_output=True, timeout=120)
            if r.returncode:
                raise RuntimeError(r.stderr.decode(errors="replace")[-300:])
            cmd = (f"pct exec {vmid} -- bash -c {shlex.quote(f'mkdir -p {d} && rm -f {d}/{remove_pattern}')} && pct push {vmid} {tmp} {d}/{zip_path.name} && "
                   f"pct exec {vmid} -- bash -c {shlex.quote(f'chown --reference={home}/agent {d} {d}/{zip_path.name} 2>/dev/null; ls -la {d}')}; rm -f {tmp}")
            r = subprocess.run(_ssh_base(settings.pve_ssh_key) + [node, cmd], capture_output=True, timeout=180)
        else:
            key = settings.target_ssh_key
            pre = f"mkdir -p {shlex.quote(d)} && rm -f {d}/{remove_pattern}"
            r = subprocess.run(_ssh_base(key) + [target, pre], capture_output=True, timeout=120)
            if r.returncode:
                raise RuntimeError(r.stderr.decode(errors="replace")[-300:])
            r = subprocess.run(_scp_base(key) + [str(zip_path), f"{target}:{d}/{zip_path.name}"], capture_output=True, timeout=180)
        if r.returncode:
            raise RuntimeError((r.stderr or r.stdout).decode(errors="replace")[-300:])
        out["published"] = True
        out["path"] = f"{d}/{zip_path.name}"
        out["listing"] = r.stdout.decode(errors="replace")[-600:]
    except Exception as e:
        out["error"] = str(e)
    return out


def customer_cert_served(settings: Settings, zip_name: str) -> tuple[bool, str]:
    """Does the MID web server hand the zip out? (static files need no API key)"""
    import requests
    import urllib3
    urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)   # the MID listener has a self-signed certificate
    url = f"https://{settings.mid_host}:{settings.mid_ws_port}/static/cert/customer/{zip_name}"
    try:
        r = requests.head(url, verify=False, timeout=20)
        return r.status_code == 200, f"{url} -> HTTP {r.status_code}"
    except requests.RequestException as e:
        return False, f"{url} -> {e}"
